"""Match a connected TV to a Gathin per-model debloat profile (suggestions only).

Data: data/cleanyourtv/device-profiles.json, generated by scripts/sync_device_profiles.py
from the pinned Gathin23/cleanyourtv commit (MIT). Profiles come from single units with
little real-world use, so they are only ever shown as suggestions, never applied for the user.
"""
from __future__ import annotations

import json
import os
import re
from typing import Any, Dict, List, Optional, Tuple

import paths

# Packages a profile may list but that this app never suggests disabling from here:
# the stock/launcher switch has its own verified flow (theme_manager.disable_stock_launcher).
NEVER_SUGGEST_PREFIXES = ("com.mediatek.",)
NEVER_SUGGEST_EXACT = {
    "com.google.android.apps.tv.launcherx",
    "com.google.android.tvlauncher",
    "com.google.android.leanbacklauncher",
    "com.google.android.tungsten.setupwraith",
}
# Too generic to identify a model on their own.
GENERIC_TOKENS = {
    "androidtv", "googletv", "smarttv", "tv", "box", "stick", "mediatek", "amlogic", "realtek",
    "google", "android", "chromecast",
}
# Devices whose clean-up is handled by this app's own flow, not by upstream profiles.
# Chromecast with Google TV: launcherx + setupwraith are switched by theme_manager
# (verified on hardware); the upstream list also touches casting-related packages.
OPT_OUT_MARKERS = ("chromecast",)
MIN_TOKEN_LEN = 4
MIN_CONTAINS_LEN = 6


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", (s or "").lower())


class DeviceProfiles:
    def __init__(self) -> None:
        self._doc = self._load()
        self.profiles: List[dict] = self._doc.get("profiles") or []

    @staticmethod
    def _load() -> dict:
        path = os.path.join(paths.app_root(), "data", "cleanyourtv", "device-profiles.json")
        try:
            with open(path, encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {}

    @property
    def commit(self) -> str:
        return self._doc.get("commit") or ""

    @staticmethod
    def never_suggest(package: str) -> bool:
        p = (package or "").lower()
        return p in NEVER_SUGGEST_EXACT or p.startswith(NEVER_SUGGEST_PREFIXES)

    def match(self, identity: Dict[str, str]) -> Tuple[Optional[dict], str]:
        """identity: manufacturer, brand, model, device, name. Returns (profile, "exact"|"likely"|"")."""
        if any(m in norm(v) for v in identity.values() for m in OPT_OUT_MARKERS):
            return None, ""
        brands = {norm(identity.get("manufacturer", "")), norm(identity.get("brand", ""))} - {""}
        ids = {
            norm(identity.get(k, "")) for k in ("model", "device", "name")
        }
        ids = {i for i in ids if len(i) >= MIN_TOKEN_LEN and i not in GENERIC_TOKENS}
        if not brands or not ids:
            return None, ""
        best: Tuple[int, int, Optional[dict], str] = (0, 0, None, "")
        for prof in self.profiles:
            pb = norm(prof.get("brand", ""))
            if not pb or not any(pb in b or b in pb for b in brands):
                continue
            toks = [t for t in prof.get("tokens") or [] if t not in GENERIC_TOKENS]
            for ident in ids:
                for t in toks:
                    bare = t[len(pb):] if t.startswith(pb) else t  # "panasonic4ktvjup" -> "4ktvjup"
                    if ident == t or ident == bare:
                        rank, quality = 2, "exact"
                    elif len(ident) >= MIN_CONTAINS_LEN and ident in t and len(ident) * 2 >= len(t) - len(pb):
                        rank, quality = 1, "likely"
                    else:
                        continue
                    cand = (rank, len(ident), prof, quality)
                    if cand[:2] > best[:2]:
                        best = cand
        return best[2], best[3]

    @staticmethod
    def package_notes(profile: dict) -> Dict[str, str]:
        out: Dict[str, str] = {}
        for item in profile.get("pkgs") or []:
            pkg = (item.get("p") or "").strip()
            if pkg and not DeviceProfiles.never_suggest(pkg):
                out[pkg] = (item.get("n") or "").strip()
        return out

    def describe(self, profile: dict, quality: str, matched: int) -> Dict[str, Any]:
        return {
            "id": profile.get("id"),
            "tv": profile.get("tv"),
            "os": profile.get("os"),
            "notes": profile.get("notes"),
            "warnings": profile.get("warnings") or [],
            "match": quality,
            "matched_packages": matched,
            "url": f"https://github.com/Gathin23/cleanyourtv/tree/{self.commit}/examples/{profile.get('id')}",
        }
